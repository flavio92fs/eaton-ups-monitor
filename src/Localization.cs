        if(language!="it" && language!="en")language=CultureInfo.CurrentUICulture.TwoLetterISOLanguageName=="it"?"it":"en";
        IsItalian=language=="it";
        var culture=CultureInfo.GetCultureInfo(IsItalian?"it-IT":"en-US");
        Thread.CurrentThread.CurrentCulture=culture;Thread.CurrentThread.CurrentUICulture=culture;
        CultureInfo.DefaultThreadCurrentCulture=culture;CultureInfo.DefaultThreadCurrentUICulture=culture;
    }
    public static void Save(string language)
    {
        if(language!="it" && language!="en")throw new ArgumentException("Unsupported language");
        using(var key=Registry.CurrentUser.CreateSubKey("Software\\EatonMonitorPersonal"))key.SetValue("Language",language);
    }
